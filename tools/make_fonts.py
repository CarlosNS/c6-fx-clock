"""Turns the two pixel fonts of the Marea Solsticial style into 1-bit bitmaps for the firmware.

    python tools/make_fonts.py        -> src/ui_fonts.c

- Jersey 10 (display: titles, numbers, buttons) at its native grid: 1400/75 px per em, so one font
  pixel is one screen pixel (capitals are 10 px tall, strokes 2 px).
- VT323 (text: labels, data) at 25 px, where its 80 x 40 unit "pixels" become 2 x 1 screen pixels.

Both are pixel fonts, so the firmware draws them enlarged by whole numbers (ui.c) and they stay sharp.
The TTFs and their SIL Open Font License texts are in tools/fonts/ (from github.com/google/fonts).
"""
import os

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "tools", "fonts")
OUT = os.path.join(ROOT, "src", "ui_fonts.c")

# ASCII plus what Spanish (and English) text needs
CHARS = "".join(chr(c) for c in range(32, 127)) + "¡¿ÁÉÍÓÚÜÑáéíóúüñ°·ºª«»€…–—×"

SETS = [
    ("ui_jersey", "Jersey10-Regular.ttf", 1400 / 75),
    ("ui_vt", "VT323-Regular.ttf", 25),
]


def build(name, file, size):
    path = os.path.join(FONTS, file)
    cmap = TTFont(path).getBestCmap()
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    glyphs, bits = [], bytearray()
    for ch in CHARS:
        if ord(ch) not in cmap:
            continue
        adv = round(font.getlength(ch))
        box = font.getbbox(ch, anchor="la")  # relative to the left of the line's top (ascender)
        w, h = box[2] - box[0], box[3] - box[1]
        off = len(bits)
        if w > 0 and h > 0:
            im = Image.new("1", (w, h), 0)
            d = ImageDraw.Draw(im)
            d.fontmode = "1"
            d.text((-box[0], -box[1]), ch, font=font, fill=1, anchor="la")
            for y in range(h):
                row = 0
                for x in range(w):
                    if im.getpixel((x, y)):
                        row |= 1 << x
                bits += row.to_bytes((w + 7) // 8, "little")
        else:
            w = h = 0
            box = (0, 0, 0, 0)
        glyphs.append((ord(ch), w, h, box[0], box[1], adv, off))
    glyphs.sort()  # by code point: ui.c looks them up by binary search
    return glyphs, bits, ascent, descent


def main():
    out = ["// Generated by tools/make_fonts.py from Jersey 10 and VT323 (SIL Open Font License 1.1,",
           "// see THIRD-PARTY-NOTICES.md). Do not edit.",
           '#include "ui_fonts.h"', ""]
    for name, file, size in SETS:
        glyphs, bits, ascent, descent = build(name, file, size)
        out.append(f"static const uint8_t {name}_bits[{len(bits)}] = {{")
        for i in range(0, len(bits), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const ui_glyph_t {name}_glyphs[{len(glyphs)}] = {{")
        for cp, w, h, xo, yo, adv, off in glyphs:
            out.append(f"    {{0x{cp:04x}, {w}, {h}, {xo}, {yo}, {adv}, {off}}},")
        out.append("};")
        out.append(f"const ui_font_t {name} = {{{name}_glyphs, {len(glyphs)}, {name}_bits, {ascent}, {descent}}};")
        out.append("")
        print(f"{name}: {len(glyphs)} glyphs, {len(bits)} bytes, ascent {ascent}, descent {descent}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print(OUT)


if __name__ == "__main__":
    main()
