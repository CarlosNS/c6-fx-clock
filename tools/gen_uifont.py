"""Generates src/uifont.c: small anti-aliased proportional UI text (ASCII 32..126).

Uses Aileron Regular, the public-domain (CC0) font bundled with Pillow. Same pixel format as
the clock digits: high nibble = coverage, low nibble = 1 px outline coverage.

Usage: python tools/gen_uifont.py
"""
import math
import os
from PIL import Image, ImageDraw, ImageFilter, ImageFont

SIZES = {"ui_s": (11, 0), "ui_m": (15, 1)}  # name: (px size, extra stroke for weight)
PAD = 1


def build(name, size, stroke):
    font = ImageFont.load_default(size)
    ascent, descent = font.getmetrics()
    h = ascent + descent
    advs, widths, offs, data = [], [], [], bytearray()
    for code in range(32, 127):
        ch = chr(code)
        adv = max(1, math.ceil(font.getlength(ch) + stroke))
        w = adv + 2 * PAD
        img = Image.new("L", (w, h + 2 * PAD), 0)
        ImageDraw.Draw(img).text((PAD, PAD), ch, font=font, fill=255, stroke_width=stroke, stroke_fill=255)
        outline = img.filter(ImageFilter.MaxFilter(3))
        offs.append(len(data))
        data += bytes(((f >> 4) << 4) | (o >> 4) for f, o in zip(img.tobytes(), outline.tobytes()))
        advs.append(adv)
        widths.append(w)
    lines = [f"static const uint8_t {name}_px[{len(data)}] = {{{','.join(map(str, data))}}};",
             f"const uifont_t {name} = {{.h = {h + 2 * PAD}, .pad = {PAD},",
             f"    .adv = {{{','.join(map(str, advs))}}},",
             f"    .w = {{{','.join(map(str, widths))}}},",
             f"    .off = {{{','.join(map(str, offs))}}},",
             f"    .px = {name}_px}};", ""]
    return lines


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    lines = ["// Generated by tools/gen_uifont.py — do not edit", '#include "uifont.h"', ""]
    for name, (size, stroke) in SIZES.items():
        lines += build(name, size, stroke)
    with open(os.path.join(root, "src", "uifont.c"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("uifont.c written")


if __name__ == "__main__":
    main()
